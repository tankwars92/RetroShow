function t($text) {
    $text = (string)$text;
    if ($text === '' || !site_lang_is_en()) {
        return $text;
    }
    $map = site_lang_en_map();
    return $map[$text] ?? $text;
}

function t_html($text): string {
    return htmlspecialchars(t($text), ENT_QUOTES, 'UTF-8');
}

function t_js_attr($text): string {
    return htmlspecialchars(json_encode(t($text), JSON_UNESCAPED_UNICODE), ENT_QUOTES, 'UTF-8');
}

function t_comments_heading($count): string {
    $count = (int)$count;
    if (site_lang_is_en()) {
        return 'Comments (' . $count . '):';
    }
    return 'Комментарии (всего ' . $count . '):';
}

function t_ratings_count($count): string {
    $n = abs((int)$count);
    if (site_lang_is_en()) {
        return (string)$n . ' ' . ($n === 1 ? 'rating' : 'ratings');
    }
    $n100 = $n % 100;
    $n1 = $n % 10;
    if ($n100 > 10 && $n100 < 20) {
        $w = 'оценок';
    } elseif ($n1 === 1) {
        $w = 'оценка';
    } elseif ($n1 >= 2 && $n1 <= 4) {
        $w = 'оценки';
    } else {
        $w = 'оценок';
    }
    return (string)$n . ' ' . $w;
}

function site_lang_url(string $lang): string {
    $script = basename((string)($_SERVER['SCRIPT_NAME'] ?? 'index.php'));
    $q = $_GET;
    $q['ui_lang'] = site_lang_normalize($lang);
    return $script . '?' . http_build_query($q);
}

function site_lang_switcher_html(): string {
    if (!empty($_SESSION['user']) || !empty($_COOKIE['lang_bar_off'])) {
        return '';
    }
    $cur = site_lang();
    $ru_img = '<img src="img/flags/Russia.png" width="16" height="11" border="0" alt="RU" style="vertical-align:middle;">';
    $en_img = '<img src="img/flags/United-States.png" width="16" height="11" border="0" alt="EN" style="vertical-align:middle;">';
    if ($cur === 'ru') {
        $ru_img = '<img src="img/flags/Russia.png" width="16" height="11" border="1" alt="RU" style="vertical-align:middle; border-color:#333333;">';
    } else {
        $en_img = '<img src="img/flags/United-States.png" width="16" height="11" border="1" alt="EN" style="vertical-align:middle; border-color:#333333;">';
    }
    $ru = ($cur === 'ru')
        ? $ru_img
        : '<a href="' . htmlspecialchars(site_lang_url('ru'), ENT_QUOTES, 'UTF-8') . '">' . $ru_img . '</a>';
    $en = ($cur === 'en')
        ? $en_img
        : '<a href="' . htmlspecialchars(site_lang_url('en'), ENT_QUOTES, 'UTF-8') . '">' . $en_img . '</a>';
    $close = htmlspecialchars(t('закрыть'), ENT_QUOTES, 'UTF-8');
    $label = htmlspecialchars(t('Язык:'), ENT_QUOTES, 'UTF-8');
    return '<td style="padding: 0px 5px 0px 5px;" id="guestLangBarSep">|</td>'
        . '<td id="guestLangBar">'
        . $label . ' ' . $ru . ' | ' . $en  . ' | '
        . '&nbsp;<a href="#" title="' . $close . '" onclick="return hideGuestLangBar();">[X]</a>'
        . '</td>';
}

function site_lang_switcher_script(): string {
    $lang_alert_js = json_encode(
        t('Теперь баннер скрыт. Язык можно сменить позже в настройках аккаунта (после входа) и сохранить его там.'),
        JSON_UNESCAPED_UNICODE
    );
    return '<script language="javascript" type="text/javascript">'
        . 'function hideGuestLangBar() {'
        . 'var ids = ["guestLangBar","guestLangBarSep"];'
        . 'for (var i = 0; i < ids.length; i++) {'
        . 'var el = document.getElementById ? document.getElementById(ids[i]) : (document.all ? document.all[ids[i]] : null);'
        . 'if (el) el.style.display = "none";'
        . '}'
        . 'document.cookie = "lang_bar_off=1; path=/";'
        . 'alert(' . $lang_alert_js . ');'
        . 'window.location.reload();'
        . 'return false;'
        . '}'
        . '</script>';
}

function site_lang_apply_request(): void {
    if (!isset($_GET['ui_lang'])) {
        return;
    }
    site_lang_set((string)$_GET['ui_lang']);
    $q = $_GET;
    unset($q['ui_lang']);
    $path = (string)(parse_url((string)($_SERVER['REQUEST_URI'] ?? '/'), PHP_URL_PATH) ?: 'index.php');
    $qs = http_build_query($q);
    header('Location: ' . $path . ($qs !== '' ? '?' . $qs : ''));
    exit;
}

function site_lang_apply_user(PDO $db, $login): void {
    $login = trim((string)$login);
    if ($login === '') {
        return;
    }
    try {
        $st = $db->prepare('SELECT ui_lang FROM users WHERE login = ? LIMIT 1');
        $st->execute([$login]);
        $v = $st->fetchColumn();
        if ($v !== false && $v !== null && $v !== '') {
            site_lang_set((string)$v);
        } else {
            site_lang_set(site_lang_default());
        }
    } catch (Exception $e) {
    }
}
