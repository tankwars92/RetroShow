<?php

function site_lang_normalize($value): string {
    $value = strtolower(trim((string)$value));
    return $value === 'en' ? 'en' : 'ru';
}

function site_lang_set(string $lang): void {
    $lang = site_lang_normalize($lang);
    $_SESSION['ui_lang'] = $lang;
    $GLOBALS['__site_lang_cache'] = $lang;
    $secure = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off');
    setcookie('ui_lang', $lang, [
        'expires' => time() + 60 * 60 * 24 * 365,
        'path' => '/',
        'secure' => $secure,
        'httponly' => false,
        'samesite' => 'Lax',
    ]);
}

function site_lang_default(): string {
    global $db;
    if (isset($GLOBALS['__site_lang_default']) && $GLOBALS['__site_lang_default'] !== null && $GLOBALS['__site_lang_default'] !== '') {
        return site_lang_normalize((string)$GLOBALS['__site_lang_default']);
    }
    $fallback = 'en';
    if (isset($db) && $db instanceof PDO) {
        try {
            $st = $db->prepare('SELECT value FROM meta WHERE key = ? LIMIT 1');
            $st->execute(['ui_lang_default']);
            $v = $st->fetchColumn();
            if ($v !== false && $v !== null && $v !== '') {
                $fallback = site_lang_normalize((string)$v);
            }
        } catch (Exception $e) {
        }
    }
    $GLOBALS['__site_lang_default'] = $fallback;
    return $fallback;
}

function site_lang_default_set(string $lang): void {
    $lang = site_lang_normalize($lang);
    $GLOBALS['__site_lang_default'] = $lang;
}

function site_lang(): string {
    if (!empty($GLOBALS['__site_lang_cache'])) {
        return site_lang_normalize((string)$GLOBALS['__site_lang_cache']);
    }
    if (!empty($_SESSION['ui_lang'])) {
        $cached = site_lang_normalize($_SESSION['ui_lang']);
        $GLOBALS['__site_lang_cache'] = $cached;
        return $cached;
    }
    if (!empty($_COOKIE['ui_lang'])) {
        $cached = site_lang_normalize($_COOKIE['ui_lang']);
        $GLOBALS['__site_lang_cache'] = $cached;
        return $cached;
    }
    $cached = site_lang_default();
    $GLOBALS['__site_lang_cache'] = $cached;
    return $cached;
}

function site_lang_is_en(): bool {
    return site_lang() === 'en';
}

